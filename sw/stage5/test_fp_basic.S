// Basic FP arithmetic: FADD.S, FSUB.S, FMUL.S, FMADD.S, FADD.D, FMUL.D
// Uses exact-result cases only to avoid rounding sensitivity.
// a0 accumulates the failure count; a0 = 0 means pass.

.section .text
.globl main

main:
    li      a0, 0                   // fail counter

    // ------------------------------------------------------------------
    // Test 1: FADD.S  1.0f + 1.0f = 2.0f
    //   1.0f = 0x3F800000
    //   2.0f = 0x40000000
    // ------------------------------------------------------------------
    li      t0, 0x3F800000
    fmv.w.x ft0, t0                 // ft0 = 1.0f
    fadd.s  ft1, ft0, ft0           // ft1 = 2.0f
    fmv.x.w t1, ft1
    li      t2, 0x40000000
    beq     t1, t2, 1f
    addi    a0, a0, 1
1:

    // ------------------------------------------------------------------
    // Test 2: FMUL.S  2.0f * 3.0f = 6.0f
    //   2.0f = 0x40000000
    //   3.0f = 0x40400000
    //   6.0f = 0x40C00000
    // ------------------------------------------------------------------
    li      t0, 0x40000000
    fmv.w.x ft0, t0                 // ft0 = 2.0f
    li      t0, 0x40400000
    fmv.w.x ft1, t0                 // ft1 = 3.0f
    fmul.s  ft2, ft0, ft1           // ft2 = 6.0f
    fmv.x.w t1, ft2
    li      t2, 0x40C00000
    beq     t1, t2, 2f
    addi    a0, a0, 1
2:

    // ------------------------------------------------------------------
    // Test 3: FMADD.S  2.0f * 3.0f + 4.0f = 10.0f
    //   4.0f = 0x40800000
    //   10.0f = 0x41200000
    // ------------------------------------------------------------------
    li      t0, 0x40000000
    fmv.w.x ft0, t0                 // ft0 = 2.0f
    li      t0, 0x40400000
    fmv.w.x ft1, t0                 // ft1 = 3.0f
    li      t0, 0x40800000
    fmv.w.x ft2, t0                 // ft2 = 4.0f
    fmadd.s ft3, ft0, ft1, ft2      // ft3 = 2*3+4 = 10.0f
    fmv.x.w t1, ft3
    li      t2, 0x41200000
    beq     t1, t2, 3f
    addi    a0, a0, 1
3:

    // ------------------------------------------------------------------
    // Test 4: FSUB.S  6.0f - 4.0f = 2.0f
    // ------------------------------------------------------------------
    li      t0, 0x40C00000
    fmv.w.x ft0, t0                 // ft0 = 6.0f
    li      t0, 0x40800000
    fmv.w.x ft1, t0                 // ft1 = 4.0f
    fsub.s  ft2, ft0, ft1           // ft2 = 2.0f
    fmv.x.w t1, ft2
    li      t2, 0x40000000
    beq     t1, t2, 4f
    addi    a0, a0, 1
4:

    // ------------------------------------------------------------------
    // Test 5: FADD.D  1.0d + 1.0d = 2.0d
    //   1.0d = 0x3FF0000000000000
    //   2.0d = 0x4000000000000000
    // ------------------------------------------------------------------
    li      t0, 0x3FF0000000000000
    fmv.d.x ft0, t0                 // ft0 = 1.0d
    fadd.d  ft1, ft0, ft0           // ft1 = 2.0d
    fmv.x.d t1, ft1
    li      t2, 0x4000000000000000
    beq     t1, t2, 5f
    addi    a0, a0, 1
5:

    // ------------------------------------------------------------------
    // Test 6: FMUL.D  2.0d * 3.0d = 6.0d
    //   2.0d = 0x4000000000000000
    //   3.0d = 0x4008000000000000
    //   6.0d = 0x4018000000000000
    // ------------------------------------------------------------------
    li      t0, 0x4000000000000000
    fmv.d.x ft0, t0                 // ft0 = 2.0d
    li      t0, 0x4008000000000000
    fmv.d.x ft1, t0                 // ft1 = 3.0d
    fmul.d  ft2, ft0, ft1           // ft2 = 6.0d
    fmv.x.d t1, ft2
    li      t2, 0x4018000000000000
    beq     t1, t2, 6f
    addi    a0, a0, 1
6:

    ret
