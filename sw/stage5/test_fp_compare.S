// FP compare and classify: FEQ.S, FLT.S, FLE.S, FMIN.S, FMAX.S, FCLASS.S
// a0 accumulates the failure count; a0 = 0 means pass.

.section .text
.globl main

main:
    li      a0, 0                   // fail counter

    // Load 1.0f and 2.0f into ft0, ft1
    li      t0, 0x3F800000
    fmv.w.x ft0, t0                 // ft0 = 1.0f
    li      t0, 0x40000000
    fmv.w.x ft1, t0                 // ft1 = 2.0f

    // ------------------------------------------------------------------
    // Test 1: FEQ.S  1.0f == 1.0f → 1
    // ------------------------------------------------------------------
    feq.s   t1, ft0, ft0
    li      t2, 1
    beq     t1, t2, 1f
    addi    a0, a0, 1
1:

    // ------------------------------------------------------------------
    // Test 2: FEQ.S  1.0f == 2.0f → 0
    // ------------------------------------------------------------------
    feq.s   t1, ft0, ft1
    beq     t1, zero, 2f
    addi    a0, a0, 1
2:

    // ------------------------------------------------------------------
    // Test 3: FLT.S  1.0f < 2.0f → 1
    // ------------------------------------------------------------------
    flt.s   t1, ft0, ft1
    li      t2, 1
    beq     t1, t2, 3f
    addi    a0, a0, 1
3:

    // ------------------------------------------------------------------
    // Test 4: FLT.S  2.0f < 1.0f → 0
    // ------------------------------------------------------------------
    flt.s   t1, ft1, ft0
    beq     t1, zero, 4f
    addi    a0, a0, 1
4:

    // ------------------------------------------------------------------
    // Test 5: FLE.S  1.0f <= 1.0f → 1
    // ------------------------------------------------------------------
    fle.s   t1, ft0, ft0
    li      t2, 1
    beq     t1, t2, 5f
    addi    a0, a0, 1
5:

    // ------------------------------------------------------------------
    // Test 6: FMIN.S  min(1.0f, 2.0f) → 1.0f = 0x3F800000
    // ------------------------------------------------------------------
    fmin.s  ft2, ft0, ft1
    fmv.x.w t1, ft2
    li      t2, 0x3F800000
    beq     t1, t2, 6f
    addi    a0, a0, 1
6:

    // ------------------------------------------------------------------
    // Test 7: FMAX.S  max(1.0f, 2.0f) → 2.0f = 0x40000000
    // ------------------------------------------------------------------
    fmax.s  ft2, ft0, ft1
    fmv.x.w t1, ft2
    li      t2, 0x40000000
    beq     t1, t2, 7f
    addi    a0, a0, 1
7:

    // ------------------------------------------------------------------
    // Test 8: FCLASS.S on a positive normal number (1.0f)
    //   For a positive normal, bit 6 of the result is set → value = 0x40
    // ------------------------------------------------------------------
    fclass.s t1, ft0
    andi    t1, t1, 0x40            // mask bit 6
    li      t2, 0x40
    beq     t1, t2, 8f
    addi    a0, a0, 1
8:

    ret
